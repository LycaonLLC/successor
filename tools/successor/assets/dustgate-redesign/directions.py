"""Three from-zero Dustgate direction studies, rendered at equal framing.

Run one direction per Blender process so scene state cannot leak:

    blender -b -P directions.py -- a
    blender -b -P directions.py -- b
    blender -b -P directions.py -- c

Each study is built only from primitives generated by `dgkit`. No existing
Dustgate geometry, builder script, texture, or render is opened or referenced.
Output goes to the ignored proof root; nothing here touches runtime assets.

Study axes that must differ, not just palette:
  A "Leeward Terrace" - linear settlement in the lee of one ancient wall,
      monopitch roofs on a shared eave datum, single long interior bays.
  B "Dust Well"       - radial settlement around a shallow sink, half-buried
      cast drums with conical caps, hearth-centred radial interiors.
  C "Frame Ward"      - dispersed tall shed frames on plinths, barrel vault and
      gable roofs, two-level workshop interiors.
"""

