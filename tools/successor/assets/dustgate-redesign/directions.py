def build_b() -> dict:
    dg.reset()
    sand = dg.mat("B_sand", "#b5a382", rough=0.96)
    cast = dg.mat("B_cast", "#b2a996", rough=0.88)
    cast_dk = dg.mat("B_cast_shade", "#8d8471", rough=0.9)
    mono = dg.mat("B_monolith", "#6e6a60", rough=0.9)
    oxide = dg.mat("B_oxide_cap", "#7b3b2c", rough=0.78)
    dark = dg.mat("B_aperture", "#241f1c", rough=0.95)
    steel = dg.mat("B_steel", "#4f4c47", rough=0.5, metal=0.7)
    phos = dg.mat("B_phosphor", "#7fd6a3", rough=0.4, emission="#7fd6a3",
                  emission_strength=2.6)

    SINK_Z = -1.15
    SINK_R = 9.4
    RIM_R = 11.0
    annulus("ground_ring", 0.0, 0.0, 0.0, RIM_R, 70.0, 48, sand)
    dg.cylinder("sink_wall", 0.0, 0.0, SINK_Z, 0.0, SINK_R, cast_dk, segments=48,
                top_radius=RIM_R)
    dg.cylinder("sink_floor", 0.0, 0.0, SINK_Z - 0.08, SINK_Z, SINK_R, sand, segments=48)
    for i in range(8):
        a = 2 * math.pi * i / 8 + 0.19
        dg.boxm(f"sink_step_{i:02d}", -0.9, 0.9, -0.7, 0.7, SINK_Z, SINK_Z + 0.35, cast_dk,
                chamfer=0.3, corner_segments=2)
        step = bpy.context.scene.objects[f"sink_step_{i:02d}"]
        step.location = (math.cos(a) * (SINK_R - 1.4), math.sin(a) * (SINK_R - 1.4), 0.0)

    def drum(prefix, cx, cy, radius, z0, wall_top, cap_top, cap_radius, door_angle,
             segments=28):
        dg.cylinder(f"{prefix}_shell", cx, cy, z0, wall_top, radius, cast, segments=segments)
        dg.cylinder(f"{prefix}_shell_band", cx, cy, wall_top - 0.42, wall_top + 0.06,
                    radius + 0.14, cast_dk, segments=segments)
        dg.cylinder(f"{prefix}_cap", cx, cy, wall_top + 0.06, cap_top, radius + 0.02, oxide,
                    segments=segments, top_radius=cap_radius)
        dg.cylinder(f"{prefix}_floor", cx, cy, z0 - 0.05, z0 + 0.02, radius - 0.3, cast_dk,
                    segments=segments)
        dg.cylinder(f"{prefix}_interior", cx, cy, z0 + 0.02, z0 + 0.06, radius - 0.42, dark,
                    segments=segments)
        # threshold reveal: a dark recess block set into the shell, footprint-only
        dx, dy = math.cos(door_angle), math.sin(door_angle)
        door = dg.boxm(f"{prefix}_door_reveal", -1.0, 1.0, -0.45, 0.45, z0, z0 + 2.25, dark)
        door.location = (cx + dx * (radius - 0.1), cy + dy * (radius - 0.1), 0.0)
        door.rotation_euler = (0.0, 0.0, door_angle - math.pi * 0.5)
        jamb = dg.boxm(f"{prefix}_door_jamb", -1.25, 1.25, -0.2, 0.2, z0, z0 + 2.55, cast_dk)
        jamb.location = (cx + dx * (radius + 0.16), cy + dy * (radius + 0.16), 0.0)
        jamb.rotation_euler = (0.0, 0.0, door_angle - math.pi * 0.5)

    # cloning drum: tall lantern + vent stack
    drum("clone", -9.6, 5.0, 5.4, SINK_Z, 3.2, 5.0, 1.5, -math.pi * 0.62)
    dg.cylinder("clone_lantern", -9.6, 5.0, 5.0, 6.0, 1.5, cast, segments=20)
    dg.cylinder("clone_lantern_cap", -9.6, 5.0, 6.0, 6.5, 1.6, oxide, segments=20,
                top_radius=0.6)
    dg.boxm("clone_lantern_glass", -10.9, -8.3, 3.86, 3.98, 5.15, 5.85, phos)
    dg.cylinder("clone_vent", -14.2, 7.4, SINK_Z, 7.6, 0.55, steel, segments=14)
    dg.cylinder("clone_vent_hood", -14.2, 7.4, 7.6, 8.3, 0.75, oxide, segments=14,
                top_radius=0.3)
    for i, a in enumerate((-2.2, -1.55, -0.9)):
        px, py = -9.6 + math.cos(a) * 5.9, 5.0 + math.sin(a) * 5.9
        dg.cylinder(f"clone_pod_{i:02d}", px, py, SINK_Z, SINK_Z + 2.4, 1.05, cast_dk,
                    segments=16)
        dg.cylinder(f"clone_pod_cap_{i:02d}", px, py, SINK_Z + 2.4, SINK_Z + 3.0, 1.05,
                    oxide, segments=16, top_radius=0.45)

    # commerce drum: broad shade brim over its whole footprint
    drum("mkt", 7.4, 3.4, 6.2, SINK_Z, 2.9, 4.5, 2.1, -math.pi * 0.78, segments=32)
    dg.cylinder("mkt_brim", 7.4, 3.4, 2.96, 3.3, 8.1, cast_dk, segments=32, top_radius=7.7)
    for i in range(6):
        a = 2 * math.pi * i / 6 + 0.3
        dg.cylinder(f"mkt_brim_post_{i:02d}", 7.4 + math.cos(a) * 7.5,
                    3.4 + math.sin(a) * 7.5, SINK_Z, 2.98, 0.14, steel, segments=8)
    dg.cylinder("mkt_vault", 13.6, 8.0, 0.0, 3.5, 2.6, mono, segments=20, top_radius=2.35)
    dg.cylinder("mkt_vault_cap", 13.6, 8.0, 3.5, 3.9, 2.45, steel, segments=20,
                top_radius=1.9)
    dg.boxm("mkt_vault_hatch", 11.2, 11.42, 7.1, 8.9, 0.0, 2.2, steel)

    # shelter drum: small, on the rim, outside the sink
    drum("hab", 1.2, -12.0, 3.6, 0.0, 2.4, 3.5, 1.1, math.pi * 0.5, segments=22)
    dg.cylinder("hab_cistern", 5.3, -13.6, 0.0, 2.0, 1.05, cast_dk, segments=16)
    dg.cylinder("hab_cistern_cap", 5.3, -13.6, 2.0, 2.4, 1.05, oxide, segments=16,
                top_radius=0.45)

    # --- ancient ribs: three colossal buried arc segments around the rim ---
    for i, (cx, cy, yaw, radius, flat, height_base) in enumerate((
        (-3.0, 21.0, 6.0, 8.6, 1.42, -2.6),
        (-21.5, 6.5, 68.0, 7.4, 1.30, -2.2),
        (19.5, 14.0, -42.0, 6.6, 1.18, -2.0),
    )):
        profile = dg.arc_profile(radius, 11, height_base, 0.0, 0.0, flat)
        rib = dg.prism(f"ancient_rib_{i:02d}", profile, "y", -1.5, 1.5, mono)
        rib.location = (cx, cy, 0.0)
        rib.rotation_euler = (0.0, 0.0, math.radians(yaw))
        core = dg.arc_profile(radius - 2.0, 11, height_base, 0.0, 0.0, flat * 0.94)
        inner = dg.prism(f"ancient_rib_core_{i:02d}", core, "y", -1.56, -1.42, cast_dk)
        inner.location = (cx, cy, 0.0)
        inner.rotation_euler = (0.0, 0.0, math.radians(yaw))

    dg.boxm("travel_pad", -1.1, 0.9, -6.2, -4.6, SINK_Z, SINK_Z + 0.28, cast_dk,
            chamfer=0.2, corner_segments=2)
    dg.cylinder("travel_column", -0.1, -5.4, SINK_Z + 0.28, 4.4, 0.42, cast, segments=16)
    dg.cylinder("travel_head", -0.1, -5.4, 4.4, 5.0, 0.62, oxide, segments=16,
                top_radius=0.28)
    dg.boxm("travel_screen", -0.6, 0.4, -5.86, -5.76, 1.0, 1.7, phos)

    proxies = scale_proxies(
        ((-5.0, 1.2), (1.6, -1.4), (1.2, -8.2), (-0.1, -4.2), (7.0, -2.6)),
        dg.mat("B_proxy", "#d7d9d4", rough=0.6),
    )
    return {"name": "b", "label": "Dust Well", "proxies": proxies,
            "gameplay_target": (1.0, 0.4, 0.6)}


