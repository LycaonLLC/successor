def main() -> None:
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else ["a"]
    key = argv[0].lower()
    study = BUILDERS[key]()
    name = study["name"]

    dg.setup_world()
    dg.add_sun(azimuth_deg=215.0, elevation_deg=54.0)
    dg.configure_render(res_x=1600, res_y=900, samples=48)

    wide = dg.add_camera(f"cam_wide_{name}", STUDY_TARGET, STUDY_WIDE_FRUSTUM)
    plan = dg.add_ortho_camera_axis(f"cam_plan_{name}", STUDY_TARGET, "top",
                                   STUDY_PLAN_FRUSTUM)
    play = dg.add_camera(f"cam_play_{name}", study["gameplay_target"],
                         STUDY_GAMEPLAY_FRUSTUM)

    meshes = dg.mesh_objects()
    bounds = dg.world_bounds(meshes)
    tris = dg.triangle_count(meshes)
    print(
        f"[direction {name}] {study['label']}: meshes={len(meshes)} tris={tris} "
        f"materials={len(bpy.data.materials)} bounds={bounds}"
    )

    dg.render_to(proof("directions", f"dir_{name}_wide.png"), wide, 1600, 900)
    dg.render_to(proof("directions", f"dir_{name}_plan.png"), plan, 1200, 1200)
    dg.render_to(proof("directions", f"dir_{name}_gameplay.png"), play, 1280, 720)
    dg.save_blend(proof("blend", f"dustgate_dir_{name}.blend"))


if __name__ == "__main__":
    main()
