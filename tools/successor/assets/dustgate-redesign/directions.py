STUDY_TARGET = (0.0, 2.0, 1.6)
STUDY_WIDE_FRUSTUM = 34.0
STUDY_PLAN_FRUSTUM = 44.0
STUDY_GAMEPLAY_FRUSTUM = 12.5  # 100% zoom
PROXY_HEIGHT = 1.75
PROXY_RADIUS = 0.3  # matches the 300 milli-cell authority movement circle


def scale_proxies(spots, material) -> list:
    return [
        dg.capsule(f"proxy__{i:02d}", x, y, 0.0, PROXY_RADIUS, PROXY_HEIGHT, material)
        for i, (x, y) in enumerate(spots)
    ]


def annulus(name, cx, cy, z, r_in, r_out, segments, material):
    """Flat ring, used where a pit must not be covered by the ground plane."""
    inner = dg.circle_poly(cx, cy, r_in, segments)
    outer = dg.circle_poly(cx, cy, r_out, segments)
    verts = [(x, y, z) for x, y in inner] + [(x, y, z) for x, y in outer]
    faces = []
    for i in range(segments):
        j = (i + 1) % segments
        faces.append((i, j, segments + j, segments + i))
    return dg.mesh_from(name, verts, faces, material, recalc=False)


